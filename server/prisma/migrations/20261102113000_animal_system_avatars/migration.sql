  ('fff271341aef2c40-large-round-ear-fox'),
  ('ffff0a6eb615d62b-small-ear-hamster');

DO $migration$
DECLARE
  target RECORD;
  picked RECORD;
BEGIN
  IF (SELECT count(*) FROM "SystemAvatar" a JOIN animal_avatar_ids k ON k.id = a.id) <> 1885 THEN
    RAISE EXCEPTION 'Animal avatar catalog is incomplete; no user avatars were changed';
  END IF;

  -- Execute a fresh random selection for each affected user. An uncorrelated
  -- LATERAL subquery would reuse one selection for every existing user.
  FOR target IN
    SELECT u.id FROM "User" u
    WHERE u."avatarSource" = 'system'
      AND NOT EXISTS (SELECT FROM animal_avatar_ids k WHERE k.id = u."systemAvatarId")
    ORDER BY u.id
  LOOP
    SELECT a.id, a."publicUrl" INTO STRICT picked
    FROM "SystemAvatar" a JOIN animal_avatar_ids k ON k.id = a.id
    ORDER BY random()
    LIMIT 1;

    UPDATE "User"
    SET "avatarUrl" = picked."publicUrl",
        "systemAvatarId" = picked.id,
        "updatedAt" = CURRENT_TIMESTAMP
    WHERE id = target.id;
  END LOOP;
END $migration$;

-- References have been changed first, so the existing FK still protects users.
DELETE FROM "SystemAvatar" a
WHERE NOT EXISTS (SELECT FROM animal_avatar_ids k WHERE k.id = a.id);
COMMIT;
