import { describe, expect, it } from "vitest"
import { HallService } from "../hall.service"
import { createHallStore } from "./hall-store"
const now = new Date(0)
const active = (overrides = {}) => ({ admissionId: "old", userId: "u", gameKind: "other", gameRoomId: "room", funding: "points" as const, ...overrides })
const record = (overrides = {}) => ({ sourceId: "roll", gameKind: "other", gameRoomId: "room", settlementId: "hand", userId: "u", admissionId: "old", funding: "points" as const, amount: 7, ...overrides })
describe("通用冻结资产的原入座身份与点数守恒", () => {
  it("冻结幂等但拒绝不同金额，关闭入座的待结算点数进入同一汇总且阻止补助", async () => {
    const db = createHallStore(0), hall = new HallService(db.prisma)
    await db.transaction(tx => hall.freezeTransfers(tx, [record()], now))
    await db.transaction(tx => hall.freezeTransfers(tx, [record()], now))
    expect(db.transfers).toHaveLength(1)
    await expect(db.transaction(tx => hall.freezeTransfers(tx, [record({ amount: 8 })], now))).rejects.toThrow()
    expect((await hall.overview("u", now)).points).toEqual({ total: 7, available: 0, inPlay: 0, pending: 7, netProfit: 7 })
    await expect(hall.grant("u", now)).rejects.toThrow()
  })
  it("相同存活入座只标table，最终筹码已含补偿不重复增加", async () => {
    const db = createHallStore(100), hall = new HallService(db.prisma)
    await db.transaction(tx => hall.join(tx, "u", { admissionId: "old", gameKind: "other", gameRoomId: "room", roomCode: "1234", seatNo: 0, buyIn: 50 }, now))
    await db.transaction(tx => hall.freezeTransfers(tx, [record()], now))
    db.sessions[0].inPlay = 57
    const released = await db.transaction(tx => hall.releaseTransfers(tx, "hand", [active()], now))
    expect(released).toMatchObject([{ amount: 7, admissionId: "old", status: "released", releasedTo: "table" }])
    expect(db.sessions[0].inPlay).toBe(57)
    expect(db.account.points).toBe(50)
    expect((await hall.overview("u", now)).points).toMatchObject({ total: 107, pending: 0, netProfit: 7 })
    expect(await db.transaction(tx => hall.releaseTransfers(tx, "hand", [active()], now))).toEqual([])
  })
  it("离座再入座复用session仍将旧补偿兑入原账号，不改新入座", async () => {
    const db = createHallStore(100), hall = new HallService(db.prisma)
    const join = { gameKind: "other", gameRoomId: "room", roomCode: "1234", seatNo: 0, buyIn: 50 }
    await db.transaction(tx => hall.join(tx, "u", { ...join, admissionId: "old" }, now))
    await db.transaction(tx => hall.freezeTransfers(tx, [record()], now))
    await db.transaction(tx => hall.leave(tx, "u", "other", "room", 50, now))
    await db.transaction(tx => hall.join(tx, "u", { ...join, admissionId: "new" }, now))
    expect((await hall.overview("u", now)).points).toEqual({ total: 107, available: 50, inPlay: 50, pending: 7, netProfit: 7 })
    await db.transaction(tx => hall.releaseTransfers(tx, "hand", [active(), active({ admissionId: "new" })], now))
    expect(db.sessions).toHaveLength(1)
    expect(db.sessions[0]).toMatchObject({ admissionId: "new", inPlay: 50 })
    expect(db.account).toMatchObject({ points: 57, netProfit: 7 })
    expect(db.transfers[0]).toMatchObject({ releasedTo: "account", status: "released" })
  })
  it("active集合不能把其他账号或其他房间的同名身份当成存活入座", async () => {
    const db = createHallStore(0), hall = new HallService(db.prisma)
    db.sessions.push({ userId: "other", gameKind: "other", gameRoomId: "room", admissionId: "old", status: "active", funding: "points", inPlay: 20 })
    await db.transaction(tx => hall.freezeTransfers(tx, [record()], now))
    await expect(db.transaction(tx => hall.voidTransfers(tx, "hand", now))).rejects.toThrow()
    await db.transaction(tx => hall.releaseTransfers(tx, "hand", [active()], now))
    expect(db.account).toMatchObject({ points: 7, netProfit: 7 })
    expect(db.sessions[0].inPlay).toBe(20)
    expect(db.transfers[0].releasedTo).toBe("account")
  })
  it("无大厅会话的练习参与者可按完整可信入座身份领到桌内补偿，不创建账号", async () => {
    const db = createHallStore(0), hall = new HallService(db.prisma)
    await db.transaction(tx => hall.freezeTransfers(tx, [record({ userId: "bot", funding: "practice" })], now))
    const released = await db.transaction(tx => hall.releaseTransfers(tx, "hand", [active({ userId: "bot", funding: "practice" })], now))
    expect(released).toMatchObject([{ status: "released", releasedTo: "table", amount: 7 }])
    expect(db.sessions).toEqual([])
    expect(db.accounts.has("bot")).toBe(false)
  })
  it.each([{ userId: "wrong" }, { gameRoomId: "wrong" }, { gameKind: "wrong" }, { funding: "points" }, { admissionId: "wrong" }])("练习可信入座任一字段不匹配则丢弃：%j", async (wrong) => {
    const db = createHallStore(0), hall = new HallService(db.prisma)
    await db.transaction(tx => hall.freezeTransfers(tx, [record({ userId: "bot", funding: "practice" })], now))
    const released = await db.transaction(tx => hall.releaseTransfers(tx, "hand", [active({ userId: "bot", funding: "practice", ...wrong })], now))
    expect(released).toMatchObject([{ status: "voided", releasedTo: "discard" }])
    expect(db.accounts.has("bot")).toBe(false)
  })
  it("完整处理超过一页的资产，多账号有序锁，练习离座丢弃且不建账号", async () => {
    const db = createHallStore(0), hall = new HallService(db.prisma)
    for (let i = 0; i < 125; i++) await db.transaction(tx => hall.freezeTransfers(tx, [record({ sourceId: String(i), userId: i % 2 ? "z" : "a", amount: 1 })], now))
    await db.transaction(tx => hall.freezeTransfers(tx, [record({ sourceId: "practice", userId: "bot", funding: "practice" })], now))
    db.locks.length = 0
    const result = await db.transaction(tx => hall.releaseTransfers(tx, "hand", [], now))
    expect(result).toHaveLength(126)
    expect(db.accounts.get("a")?.points).toBe(63)
    expect(db.accounts.get("z")?.points).toBe(62)
    expect(db.accounts.has("bot")).toBe(false)
    expect(db.locks).toEqual(["a", "z"])
    expect(db.transfers.find(t => t.userId === "bot")).toMatchObject({ status: "voided", releasedTo: "discard" })
  })
  it("只冻结正整数且每批至多十个收款人，取消练习资产保留丢弃审计", async () => {
    const db = createHallStore(), hall = new HallService(db.prisma)
    for (const amount of [0, -1, 1.5, Number.MAX_SAFE_INTEGER]) await expect(db.transaction(tx => hall.freezeTransfers(tx, [record({ amount })], now))).rejects.toThrow()
    await expect(db.transaction(tx => hall.freezeTransfers(tx, Array.from({ length: 11 }, (_, i) => record({ admissionId: String(i) })), now))).rejects.toThrow()
    await db.transaction(tx => hall.freezeTransfers(tx, [record({ funding: "practice" })], now))
    await db.transaction(tx => hall.voidTransfers(tx, "hand", now))
    expect(db.transfers[0]).toMatchObject({ status: "voided", releasedTo: "discard" })
  })
})
