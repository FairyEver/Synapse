const ESCAPE_PREFIX = '__SYNAPSE_ESC_'
const ESCAPE_LITERAL = '__SYNAPSE_ESC_L_'
const ESCAPE_SCRIPT_PREFIX = '__SYNAPSE_ESC_S_'

export function escapeCopyMarkdown(text) {
  if (!text) return ''
  // 1. Escape any pre-existing occurrences of our sentinel prefix to avoid collision
  const escapedSentinels = text.replaceAll(ESCAPE_PREFIX, ESCAPE_LITERAL)
  // 2. Replace case-insensitive </script with unique hex-encoded representation of the matched characters
  return escapedSentinels.replace(/<\/script/gi, (match) => {
    let hex = ''
    for (let i = 0; i < match.length; i++) {
      hex += match.charCodeAt(i).toString(16).padStart(2, '0')
    }
    return `${ESCAPE_SCRIPT_PREFIX}${hex}_`
  })
}

export function restoreCopyMarkdown(text) {
  if (!text) return ''
  // 1. Restore escaped closing script tags with original exact casing
  const restoredScripts = text.replace(/__SYNAPSE_ESC_S_([0-9a-f]+)_/g, (_, hex) => {
    let str = ''
    for (let i = 0; i < hex.length; i += 2) {
      str += String.fromCharCode(parseInt(hex.slice(i, i + 2), 16))
    }
    return str
  })
  // 2. Restore original sentinel literals
  return restoredScripts.replaceAll(ESCAPE_LITERAL, ESCAPE_PREFIX)
}

function stripFrontmatter(rawMarkdown) {
  return rawMarkdown.replace(/^---\r?\n[\s\S]*?\r?\n---(?:\r?\n|$)/u, '')
}

function homepageMarkdown(frontmatter) {
  const hero = frontmatter?.hero
  if (frontmatter?.layout !== 'home' || !hero) return ''

  const heading = [hero.name, hero.text].filter(Boolean).join(' ')
  const lines = heading ? [`# ${heading}`] : []

  if (hero.tagline) lines.push('', hero.tagline)

  const actions = Array.isArray(hero.actions) ? hero.actions : []
  for (const action of actions) {
    if (!action?.text || !action?.link) continue
    lines.push('', `[${action.text}](${action.link})`)
  }

  return lines.length > 0 ? `${lines.join('\n')}\n` : ''
}

export function buildCopyMarkdown(rawMarkdown, frontmatter = {}) {
  const body = stripFrontmatter(rawMarkdown)
  const markdown = body.trim() ? body : homepageMarkdown(frontmatter)
  // In HTML script blocks generated by VitePress, literal </script> closes the script tag prematurely.
  // Escaping must be strictly bijective and collision-free.
  return escapeCopyMarkdown(markdown)
}
