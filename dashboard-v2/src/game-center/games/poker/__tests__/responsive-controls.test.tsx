/** @vitest-environment jsdom */
import { act } from "react"
import { createRoot } from "react-dom/client"
import { afterEach, describe, expect, it, vi } from "vitest"
import type { PokerTableView } from "@synapse/shared/game-contracts"
import { HumanControls } from "../components/HumanControls"
import { Table } from "../components/Table"

const api = vi.hoisted(() => ({ act: vi.fn(), control: vi.fn() }))
vi.mock("../../../lib/api", () => ({ gameApi: () => ({ poker: { action: { act: api.act }, control: { set: api.control } } }) }))
Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true })
const observers = new Set<{ callback: ResizeObserverCallback; elements: Set<Element> }>()
vi.stubGlobal("ResizeObserver", class {
  elements = new Set<Element>()
  constructor(public callback: ResizeObserverCallback) { observers.add(this) }
  observe(element: Element) { this.elements.add(element) }
  unobserve(element: Element) { this.elements.delete(element) }
  disconnect() { observers.delete(this) }
})
const table: PokerTableView = { roomCode:"1234", name:null, status:"running", buyIn:1000, maxSeats:2, handId:"hand", handNo:1, street:"flop", board:[], pot:20, dealerSeat:0, actionOnSeat:0, deadlineMs:20000, cursor:"1:3", mySeatNo:0, seats:[{ seatNo:0, displayName:"本人", isMe:true, stack:100, status:"active", streetBet:2, aiState:"online", controller:"human" }], recentActions:[], deckRemaining:40, actionSeq:3, controlVersion:4, controller:"human", legalActions:["fold","call","raise","allin"], toCall:4, minRaiseTo:10, maxRaiseTo:102 }
const button = (host: ParentNode, label: string) => [...host.querySelectorAll<HTMLButtonElement>('button, [role="tab"]')].find(b => b.textContent === label || b.getAttribute("aria-label") === label)!
const click = async (host: ParentNode, label: string) => act(async () => { const target=button(host,label); if(target.getAttribute("role")==="tab") target.dispatchEvent(new MouseEvent("mousedown",{button:0,bubbles:true})); target.click() })
afterEach(() => { vi.clearAllMocks(); document.body.replaceChildren(); observers.clear() })
async function controls(value = table, compact = true) {
  const host=document.createElement("div"),root=createRoot(host)
  document.body.append(host)
  const render=async(next: PokerTableView)=>act(async()=>root.render(<HumanControls table={next} compact={compact} perspective="owner" onRefresh={vi.fn()} />))
  await render(value)
  return {host,root,render}
}

describe("窄屏精简出牌", () => {
  it("常驻档位只选择金额，主按钮明确提交且无需先展开表单", async () => {
    api.act.mockResolvedValue({ok:true})
    const {host,root}=await controls()
    expect([...host.querySelectorAll(".poker-action-buttons button")].map(b=>b.textContent)).toEqual(["弃牌","跟注 4","加注到 10"])
    expect(host.querySelector("input")).toBeNull()
    expect(button(host,"交给 AI")).toBeUndefined()
    for (const label of ["最小", "半池", "一池", "自定义"]) expect(button(host,label)).toBeDefined()
    expect(button(host,"全下")).toBeUndefined()
    await click(host,"半池")
    expect(api.act).not.toHaveBeenCalled()
    expect(host.querySelector('input[type="number"]')).toBeNull()
    expect(button(host,"确认加注 18").textContent).toBe("加注到 18")
    await click(host,"确认加注 18")
    expect(api.act).toHaveBeenCalledWith(expect.objectContaining({action:"raise",to:18,controlVersion:4}))
    await act(async()=>root.unmount())
  })
  it("默认最小额可直接确认，重复点击只提交一次", async () => {
    api.act.mockResolvedValue({ok:true})
    const {host,root}=await controls()
    await act(async()=>{button(host,"确认加注 10").click();button(host,"确认加注 10").click()})
    expect(api.act).toHaveBeenCalledExactlyOnceWith(expect.objectContaining({action:"raise",to:10}))
    await act(async()=>root.unmount())
  })
  it.each([true,false])("compact=%s 无人下注时常驻档位，确认提交下注而非加注", async compact => {
    api.act.mockResolvedValue({ok:true})
    const {host,root}=await controls({...table,legalActions:["fold","check","bet","allin"],toCall:0,minRaiseTo:4},compact)
    await click(host,"半池")
    expect(api.act).not.toHaveBeenCalled()
    expect(button(host,"确认下注 12")).toBeDefined()
    expect(host.querySelector('input[type="number"]')).toBeNull()
    await click(host,"确认下注 12")
    expect(api.act).toHaveBeenCalledExactlyOnceWith(expect.objectContaining({action:"bet",to:12}))
    await act(async()=>root.unmount())
  })
  it("外露档位达到筹码上限仍需确认全下，取消保留金额", async () => {
    api.act.mockResolvedValue({ok:true})
    const {host,root}=await controls({...table,pot:500})
    await click(host,"一池")
    await click(host,"确认加注 102")
    expect(api.act).not.toHaveBeenCalled()
    expect(host.querySelector('[role="alertdialog"]')).not.toBeNull()
    await click(host,"取消")
    expect(button(host,"确认加注 102")).toBeDefined()
    await click(host,"确认加注 102")
    await click(host,"确认全下 100")
    expect(api.act).toHaveBeenCalledExactlyOnceWith(expect.objectContaining({action:"raise",to:102}))
    await act(async()=>root.unmount())
  })
  it("自定义关闭保留选择，下一行动重置为合法最小额", async () => {
    const {host,root,render}=await controls()
    await click(host,"半池")
    await click(host,"自定义")
    expect(host.querySelector<HTMLInputElement>('input[type="number"]')?.value).toBe("18")
    await click(host,"收起加注设置")
    expect(button(host,"确认加注 18")).toBeDefined()
    await render({...table,actionSeq:4,minRaiseTo:12})
    expect(button(host,"确认加注 12")).toBeDefined()
    expect(api.act).not.toHaveBeenCalled()
    await act(async()=>root.unmount())
  })
  it("全下取消回到金额设置，确认前不提交且保留焦点", async () => {
    api.act.mockResolvedValue({ok:true})
    const {host,root}=await controls()
    await click(host,"自定义")
    button(host,"全下").focus()
    await click(host,"全下")
    expect(api.act).not.toHaveBeenCalled()
    const confirmation = host.querySelector('[role="alertdialog"]')
    expect(confirmation).not.toBeNull()
    expect(confirmation?.textContent).toContain("确认全下")
    await click(host,"取消")
    expect(host.querySelector('input[type="number"]')).not.toBeNull()
    expect(document.activeElement).toBe(button(host,"全下"))
    await click(host,"全下")
    await click(host,"确认全下 100")
    expect(api.act).toHaveBeenCalledWith(expect.objectContaining({action:"allin"}))
    await act(async()=>root.unmount())
  })
  it("没有加注资格但允许全下时保留入口，跟注耗尽筹码也需确认", async () => {
    const {host,root,render}=await controls({...table,legalActions:["fold","call","allin"]})
    await click(host,"全下")
    expect(api.act).not.toHaveBeenCalled()
    expect(button(host,"确认全下 100")).toBeDefined()
    expect(button(host,"半池")).toBeUndefined()
    await click(host,"取消")
    expect(host.querySelector('input[type="number"]')).toBeNull()
    await render({...table,toCall:100,actionSeq:4,legalActions:["fold","call"]})
    await click(host,"跟注 100")
    expect(api.act).not.toHaveBeenCalled()
    expect(button(host,"确认全下 100")).toBeDefined()
    await act(async()=>root.unmount())
  })
  it.each(["hand","sequence","control","perspective"])("%s 变化关闭旧金额弹层", async kind => {
    const {host,root,render}=await controls()
    await click(host,"自定义")
    await click(host,"全下")
    expect(host.querySelector('[role="alertdialog"]')).not.toBeNull()
    if(kind==="perspective") await act(async()=>root.render(<HumanControls table={table} compact perspective="public" onRefresh={vi.fn()} />))
    else await render({...table,...(kind==="hand"?{handId:"next"}:kind==="sequence"?{actionSeq:4}:{controlVersion:5,controller:"ai" as const})})
    expect(host.querySelector('input[type="number"]')).toBeNull()
    expect(host.querySelector('[role="alertdialog"]')).toBeNull()
    expect(api.act).not.toHaveBeenCalled()
    await act(async()=>root.unmount())
  })
  it("响应未知后关闭金额弹层仍能用原动作重试", async () => {
    api.act.mockRejectedValueOnce(new Error("响应丢失")).mockResolvedValueOnce({ok:true})
    const {host,root}=await controls()
    await click(host,"自定义")
    await click(host,"确认加注 10")
    const intent=api.act.mock.calls[0][0]
    expect(button(host,"弃牌").disabled).toBe(true)
    expect(button(host,"半池").disabled).toBe(true)
    expect(button(host,"自定义").disabled).toBe(true)
    if(button(host,"收起加注设置")) await click(host,"收起加注设置")
    await click(host,"重试出牌")
    expect(api.act.mock.calls[1][0]).toEqual(intent)
    await act(async()=>root.unmount())
  })
})

describe("统一底部操作与按需侧栏", () => {
  it("Roll与日志/金额/全下/管理互斥，关闭回入口且画布节点保持",async()=>{
    const host=document.createElement("div"),root=createRoot(host);document.body.append(host)
    const value={...table,hole:["As","Kd"],roll:{enabled:true,count:0,normal:{fee:3,available:true},super:{fee:8,available:true}}}
    await act(async()=>root.render(<Table table={value} perspective="owner" identityKey="panel-roll-user" onPerspective={()=>{}} onBack={()=>{}}/>))
    const canvas=host.querySelector('.poker-canvas'),style=canvas!.getAttribute('style')
    await click(host,"日志")
    button(host,"Roll 换牌").focus()
    await click(host,"Roll 换牌")
    expect(host.querySelector('.poker-information-drawer')!.hasAttribute('hidden')).toBe(true)
    expect(document.body.querySelector('[role="dialog"]')?.textContent).toContain("Roll 换牌")
    await click(document.body,"取消")
    await act(async()=>{await new Promise(resolve=>requestAnimationFrame(resolve))})
    expect(document.activeElement).toBe(button(host,"Roll 换牌"))
    await click(host,"自定义")
    expect(host.querySelector('input[type="number"]')).not.toBeNull()
    await click(host,"全下")
    expect(host.querySelector('[role="alertdialog"]')).not.toBeNull()
    await click(host,"Roll 换牌")
    expect(host.querySelector('[role="alertdialog"]')).toBeNull()
    expect(host.querySelector('input[type="number"]')).toBeNull()
    await click(document.body,"取消")
    await click(host,"更多牌桌操作")
    await click(host,"Roll 换牌")
    expect(button(host,"离桌")).toBeUndefined()
    expect(host.querySelector('.poker-canvas')).toBe(canvas)
    expect(canvas!.getAttribute('style')).toBe(style)
    await act(async()=>root.unmount())
  })

  it("按内容宽度切换，日志、金额和更多互斥且不改变画布尺寸", async () => {
    const host=document.createElement("div"),root=createRoot(host)
    document.body.append(host)
    await act(async()=>root.render(<Table table={table} perspective="owner" onPerspective={vi.fn()} onBack={vi.fn()} members={<span>陪练设置</span>} />))
    const surface=host.querySelector(".poker-table")!,viewport=host.querySelector(".poker-canvas-viewport")!
    const resize=async(width:number)=>act(async()=>{
      for(const observer of [...observers]) if(observer.elements.has(surface)) observer.callback([
        {target:surface,contentRect:{width,height:700}},
        {target:viewport,contentRect:{width:700,height:560}},
      ] as ResizeObserverEntry[],{} as ResizeObserver)
      await new Promise<void>(resolve => requestAnimationFrame(() => resolve()))
    })
    await resize(720)
    expect(host.querySelector("input")).toBeNull()
    await click(host,"日志")
    expect(button(host,"收起日志").getAttribute("aria-expanded")).toBe("true")
    const transform=(host.querySelector(".poker-canvas") as HTMLElement).style.transform
    await click(host,"更多牌桌操作")
    expect(button(host,"日志").getAttribute("aria-expanded")).toBe("false")
    expect(button(host,"交给 AI")).toBeDefined()
    await act(async()=>root.render(<Table table={{...table,actionSeq:4}} perspective="owner" onPerspective={vi.fn()} onBack={vi.fn()} members={<span>陪练设置</span>} />))
    expect(button(host,"交给 AI")).toBeDefined()
    await act(async()=>{ const target=button(host,"自定义"); target.dispatchEvent(new MouseEvent("pointerdown",{button:0,bubbles:true})); target.focus(); target.click() })
    await act(async()=>new Promise(resolve=>setTimeout(resolve,10)))
    expect(host.querySelector('input[type="number"]')).not.toBeNull()
    expect(button(host,"更多牌桌操作").getAttribute("aria-expanded")).toBe("false")
    expect(button(host,"交给 AI")).toBeUndefined()
    expect((host.querySelector(".poker-canvas") as HTMLElement).style.transform).toBe(transform)
    await resize(1024)
    expect(button(host,"更多牌桌操作").getAttribute("aria-expanded")).toBe("false")
    expect(host.querySelector('input[type="number"]')).toBeNull()
    await click(host,"自定义")
    expect(host.querySelector('input[type="number"]')).not.toBeNull()
    await click(host,"日志")
    await click(host,"成员管理")
    expect(host.textContent).toContain("陪练设置")
    await act(async()=>root.unmount())
  })
})
